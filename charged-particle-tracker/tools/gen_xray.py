#!/usr/bin/env python3
"""Generates data/xray.js (atomic X-ray data per element) from xraylib (pip install xraylib).
Per element Z (3..100):  e = [K, L1, L2, L3] edge energies (keV); w = [wK, wL1, wL2, wL3] fluorescence yields;
f = [f12, f13, f23] Coster-Kronig probabilities; kl = [yield of K->L2, K->L3 radiative transitions per K vacancy];
K, L1, L2, L3 = lists of [E (keV), photons per vacancy of that shell] (= fluorescence yield x radiative rate),
close lines (< 0.1 keV) merged, lines below 1e-4 per vacancy dropped."""
import re, sys, xraylib as X
names = [n for n in dir(X) if re.fullmatch(r'(K|L1|L2|L3)[LMNOP]\d?_LINE', n)]
def sf(fn, *a):
    try: return fn(*a)
    except Exception: return 0.0
def shell_lines(Z, pre, shell):
    w = sf(X.FluorYield, Z, shell); out = []
    for n in names:
        m = re.fullmatch(r'(K|L1|L2|L3)([LMNOP]\d?)_LINE', n)
        if m.group(1) != pre: continue
        if pre == 'K' and m.group(2) in ('L',): continue
        try: E = X.LineEnergy(Z, getattr(X, n)); r = X.RadRate(Z, getattr(X, n))
        except Exception: continue
        if E > 0.05 and r > 0 and w * r >= 1e-4: out.append([E, w * r, n])
    out.sort(); mg = []
    for E, p, n in out:
        if mg and E - mg[-1][0] < 0.1: q = mg[-1]; t = q[1] + p; q[0] = (q[0] * q[1] + E * p) / t; q[1] = t
        else: mg.append([E, p])
    return mg, w
res = {}
for Z in range(3, 101):
    try:
        K, wk = shell_lines(Z, 'K', X.K_SHELL); L1, w1 = shell_lines(Z, 'L1', X.L1_SHELL); L2, w2 = shell_lines(Z, 'L2', X.L2_SHELL); L3, w3 = shell_lines(Z, 'L3', X.L3_SHELL)
        kl2 = wk * sf(X.RadRate, Z, X.KL2_LINE); kl3 = wk * sf(X.RadRate, Z, X.KL3_LINE)
        res[Z] = dict(e=[round(sf(X.EdgeEnergy, Z, s), 4) for s in (X.K_SHELL, X.L1_SHELL, X.L2_SHELL, X.L3_SHELL)], w=[round(v, 5) for v in (wk, w1, w2, w3)],
                      f=[round(sf(X.CosKronTransProb, Z, t), 5) for t in (X.FL12_TRANS, X.FL13_TRANS, X.FL23_TRANS)], kl=[round(kl2, 5), round(kl3, 5)],
                      K=[[round(a, 4), float('%.5g' % b)] for a, b in K], L1=[[round(a, 4), float('%.5g' % b)] for a, b in L1], L2=[[round(a, 4), float('%.5g' % b)] for a, b in L2], L3=[[round(a, 4), float('%.5g' % b)] for a, b in L3])
    except Exception as ex: print('Z', Z, ex, file=sys.stderr)
import json
js = '/* Atomic X-ray data (edges, fluorescence yields, Coster-Kronig probabilities, line energies and yields) per element Z, generated by tools/gen_xray.py from xraylib. */\nconst XRAY = ' + json.dumps(res, separators=(',', ':')) + ';\n'
open('data/xray.js', 'w').write(js); print(len(res), 'elements', len(js) // 1024, 'kB')
