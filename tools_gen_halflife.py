"""Generates src/ui/48-half-lives.js from the mendeleev 1.3.0 isotope table (pip download mendeleev; elements.db)."""
import sqlite3, json, sys, glob
db = glob.glob('/tmp/pk/x_mendeleev*/mendeleev/elements.db')[0]
U = {'ysec':1e-24,'zsec':1e-21,'asec':1e-18,'psec':1e-12,'nsec':1e-9,'usec':1e-6,'msec':1e-3,'sec':1,'minute':60,'hour':3600,'day':86400,'year':31556926,'kyear':3.1556926e10,'Myear':3.1556926e13,'Gyear':3.1556926e16,'Tyear':3.1556926e19,'Pyear':3.1556926e22,'Eyear':3.1556926e25,'Zyear':3.1556926e28,'Yyear':3.1556926e31}
MODE = {'B-':'β−','B+':'β+','e+':'β+','EC':'EC','EC+B+':'EC/β+','A':'α','SF':'SF','p':'p','n':'n','2p':'2p','2n':'2n','3n':'3n','B-n':'β−n','B+p':'β+p','B-A':'β−α','B+A':'β+α','2B-':'2β−','2B+':'2β+','B-d':'β−d','B-SF':'β−SF','B+SF':'β+SF','3p':'3p','4n':'4n','B-t':'β−t','B-p':'β−p','B+pA':'β+pα'}
c = sqlite3.connect(db); cur = c.cursor()
T = {}; M = {}; ST = []
modes = {}
for iid, mode, rel, inten in cur.execute("select isotope_id, mode, relation, intensity from isotopedecaymodes where is_allowed_not_observed is not 1 or is_allowed_not_observed is null order by intensity desc"):
    if inten is not None and inten < 1: continue
    modes.setdefault(iid, [])
    m = MODE.get(mode, mode)
    if m not in modes[iid]: modes[iid].append(m)
for iid, Z, A, hl, unit, rad in cur.execute("select id, atomic_number, mass_number, half_life, half_life_unit, is_radioactive from isotopes"):
    za = Z * 1000 + A
    if not rad: ST.append(za); continue
    if hl is not None and unit in U: T[za] = float('%.6g' % (hl * U[unit]))
    ms = modes.get(iid, [])
    if 'EC' in ms and 'β+' in ms: ms = [m for m in ms if m not in ('EC', 'β+')] + ['EC/β+']
    if ms: M[za] = ', '.join(ms[:3])
# branching for the decay chains: per nuclide [[code, %], ...] with codes whose daughters are given by the shift table in 48-activation.js
SHIFT = {'B-','EC','A','p','n','2n','3n','4n','2p','3p','B-n','B+p','B-A','B+A','2B-','2B+','B-d','B-t','B-p','B+pA','SF','B-SF','B+SF'}
raw = {}
for iid, mode, inten in cur.execute("select isotope_id, mode, intensity from isotopedecaymodes where is_allowed_not_observed is not 1 or is_allowed_not_observed is null"):
    raw.setdefault(iid, []).append((mode, inten))
BR = {}
for iid, Z, A, rad in cur.execute("select id, atomic_number, mass_number, is_radioactive from isotopes"):
    if not rad or iid not in raw: continue
    d = {}
    for mode, inten in raw[iid]:
        if mode in ('B+', 'EC', 'EC+B+', 'e+'): key = 'EC'
        elif mode in SHIFT: key = mode
        else: continue
        d.setdefault(key, {})[mode] = inten
    br = {}
    for key, g in d.items():
        if key == 'EC':
            v = [g.get('B+'), g.get('EC'), g.get('EC+B+')]; vv = [x for x in v if x is not None]
            if not vv and g.get('e+') is not None: vv = [g['e+']]
            if vv:
                t = sum(vv); br[key] = t if t <= 100.5 else max(vv)
            else: br[key] = None
        else:
            br[key] = g.get(key)
    if len(br) > 1:
        for k in ('2B-', '2B+'): br.pop(k, None)
    known = {k: v for k, v in br.items() if v is not None}
    if known: items = list(known.items())
    elif br: items = [(list(br.keys())[0], 100.0)]
    else: continue
    tot = sum(v for k, v in items)
    if tot > 100: items = [(k, v * 100 / tot) for k, v in items]
    BR[Z * 1000 + A] = ';'.join('%s:%g' % (k, round(v, 4)) for k, v in sorted(items, key=lambda kv: -kv[1]) if v > 0)
out = '/* ====== nuclide half-lives and decay modes (generated by tools_gen_halflife.py from the isotope table of the mendeleev 1.3.0 package; T½ in seconds) ====== */\n'
out += 'const HL_T = ' + json.dumps(T, separators=(',', ':')) + ';\nconst HL_MODE = ' + json.dumps(M, ensure_ascii=False, separators=(',', ':')) + ';\nconst HL_BR = ' + json.dumps(BR, separators=(',', ':')) + ';\nconst HL_STABLE = new Set(' + json.dumps(ST, separators=(',', ':')) + ');\n'
open('/tmp/claude-0/-home-claude/f4455f09-14fc-5dfb-bbf4-c0eee58c6786/scratchpad/cpt/src/ui/48-half-lives.js', 'w').write(out)
print(len(T), len(M), len(BR), len(ST), len(out))
