#!/usr/bin/env python3
"""Builds src/ui/51-nd-data-u.js (embedded U-238 (n,f) cross section of the PPAC detector model) from the JENDL-5 ENDF-6 file
U-238-n.jendl5 (pointwise, 300 K, MF 3 / MT 18):  python3 tools/make_nd_u238.py U-238-n.jendl5"""
import sys, bisect, os, re
def num(s):
    s = s.strip()
    if not s: return 0.0
    m = re.match(r'^([+-]?\d*\.?\d*)([+-]\d+)$', s)
    return float(m.group(1) + 'e' + m.group(2)) if m and not re.search(r'[eE]', s) else float(s)
lines = []; hdr = None
with open(sys.argv[1]) as fh:
    for l in fh:
        mf, mt = l[70:72].strip(), l[72:75].strip()
        if mf == '3' and mt == '18': lines.append(l)
        elif mf == '1' and mt == '451' and hdr is None: hdr = l
assert lines, 'MF3/MT18 not found'
rec = lambda l: [l[11 * k:11 * k + 11] for k in range(6)]
h = rec(lines[1]); NR, NP = int(h[4]), int(h[5]); awr = num(rec(lines[0])[1])
vals = []
for l in lines[2:]:
    if l[72:75].strip() == '0': continue
    vals += [num(x) for x in rec(l)]
nbt_int = vals[:2 * NR]; xy = vals[2 * NR:2 * NR + 2 * NP]
E = xy[0::2]; sf = xy[1::2]
ints = sorted(set(int(v) for v in nbt_int[1::2]))
print('NP', NP, 'interpolation laws', ints, 'range', E[0], E[-1], 'sigma_f(14.1) ~', sf[bisect.bisect_left(E, 14.1)])
assert ints == [2], 'only lin-lin tables are handled'
NES = len(E)
def at(x):
    j = bisect.bisect_left(E, x)
    if j <= 0: return sf[0]
    if j >= NES: return sf[-1]
    d = E[j] - E[j - 1]
    return sf[j - 1] + (sf[j] - sf[j - 1]) * (x - E[j - 1]) / d if d > 0 else sf[j]
E_MeV = [e * 1e-6 for e in E]
r = 1.005; g = [1e-5]
while g[-1] < E_MeV[-1] / r: g.append(g[-1] * r)
g.append(E_MeV[-1])
def atM(x): return at(x * 1e6)
out = []
for a, b in zip(g[:-1], g[1:]):
    i0, i1 = bisect.bisect_left(E_MeV, a), bisect.bisect_right(E_MeV, b)
    pts = [(a, atM(a))] + [(E_MeV[k], sf[k]) for k in range(i0, i1) if a < E_MeV[k] < b] + [(b, atM(b))]
    area = sum(0.5 * (y0 + y1) * (x1 - x0) for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]))
    out.append((0.5 * (a + b), area / (b - a)))
fmt = lambda v: '%.5g' % v
js = ('/* ====== Embedded evaluated data of the PPAC detector model: JENDL-5 U-238 neutron-induced fission cross section (MF 3, MT 18) at 300 K (Iwamoto et al., J. Nucl. Sci. Technol. 60 (2023) 1),\n'
      '   averaged over a log grid of 0.5 % (bin averages of the pointwise data), generated by tools/make_nd_u238.py ====== */\n'
      'const ND_U238 = {\n  name: "JENDL-5 U-238-n.jendl5",\n  AWR: @AWR@,\n  Emax: @EMAX@, // MeV, end of the evaluation (the cross section is kept constant above)\n  E: [@E@],\n  sf: [@SF@]\n};\n')
js = js.replace('@AWR@', fmt(awr)).replace('@EMAX@', fmt(E_MeV[-1])).replace('@E@', ','.join(fmt(x) for x, _ in out)).replace('@SF@', ','.join(fmt(y) for _, y in out))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../src/ui/51-nd-data-u.js'), 'w').write(js)
print(len(out), 'points', len(js), 'bytes; max', max(y for _, y in out))
