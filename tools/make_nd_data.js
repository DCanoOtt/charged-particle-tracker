// Builds src/ui/51-nd-data.js (embedded n+1H and n+12C data of the neutron-detector model) from the ENDF/B-VIII.0 ACE files
// at 293.6 K (1001.800nc, 6012.800nc, lib80x):  node tools/make_nd_data.js 1001.800nc 6012.800nc
const fs = require('fs'), vm = require('vm'), path = require('path');
const ui = f => fs.readFileSync(path.join(__dirname, '../src/ui', f), 'utf8');
vm.runInThisContext([ui('43-endf.js'), ui('46-secondaries.js'), ui('51-nd-data.js'), ui('52-nd-engine.js')].join('\n') + ';globalThis.A={ndParseAce,d2List};');
const r = (x, n) => Number(Number(x).toPrecision(n));
const NM = 33;
function pack(d, name) {
  const E0 = d.mts[2].xs.x, E = Array.from(E0, v => r(v, 7)), mts = {};
  for (const k of Object.keys(d.mts)) {
    const m = d.mts[k], x0 = m.xs.x[0];
    let ie = 0; while (ie < E0.length && E0[ie] < x0 * 0.999999) ie++;
    mts[k] = [r(m.Q, 6), ie, ...Array.from(m.xs.y, v => r(v, 5))];
  }
  // angular distribution of the elastic channel: pdf on NM equidistant CM cosines for each tabulated energy
  const ae = [], af = [];
  d.ang.E.forEach((e, i) => {
    ae.push(r(e, 6));
    const L = d.ang.L[i];
    for (let j = 0; j < NM; j++) {
      const mu = -1 + (2 * j) / (NM - 1);
      af.push(r(A.d2List(L, mu), 4));
    }
  });
  return { ZA: d.ZA, AWR: r(d.AWR, 8), E, mts, aE: ae, aF: af };
}
const [fh, fc] = process.argv.slice(2);
const out = { H: pack(A.ndParseAce(fs.readFileSync(fh, 'utf8')), 'H'), C: pack(A.ndParseAce(fs.readFileSync(fc, 'utf8')), 'C') };
fs.writeFileSync(path.join(__dirname, '../src/ui/51-nd-data.js'),
  '/* ====== Embedded evaluated data of the neutron-detector model: ENDF/B-VIII.0 n+1H and n+12C at 293.6 K (ACE files of lib80x, Conlin et al., LA-UR-18-24034), generated by tools/make_nd_data.js ====== */\nconst ND_EMB = ' + JSON.stringify(out) + ';\n');
